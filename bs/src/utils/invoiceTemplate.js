import { amountToWords } from "./numberToWords.js";
import { readFileSync } from 'node:fs';
import { formatBS } from './bsDate.js';

const devanagariFont = readFileSync(new URL('../../node_modules/@fontsource/noto-sans-devanagari/files/noto-sans-devanagari-devanagari-400-normal.woff2', import.meta.url)).toString('base64');

const formatDate = (value, language) => {
  if (!value) return "—";
  return formatBS(value, 'long', language);
};

const escapeHtml = (str = "") =>
  String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const statusColor = (status) => {
  if (status === "paid") return "#059669";
  if (status === "partial") return "#ea580c";
  return "#dc2626";
};

export const buildInvoiceHtml = (invoice = {}, language = 'en') => {
  const currency = new Intl.NumberFormat(language === 'np' ? 'ne-NP' : 'en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const currencySymbol = language === 'np' ? 'रु.' : 'Rs.';
  const l = language === 'np' ? {
    invoice: 'कर बिजक', invoiceNo: 'बिजक नं.', billNo: 'बिल नं.', date: 'मिति', due: 'भुक्तानी मिति', billTo: 'बिल प्राप्तकर्ता', phone: 'फोन', paymentStatus: 'भुक्तानी अवस्था',
    product: 'वस्तु / सेवा', qty: 'परिमाण', unit: 'एकाइ', rate: 'दर', discount: 'छुट', total: 'जम्मा', noItems: 'कुनै वस्तु छैन', remarks: 'कैफियत', amountWords: 'अक्षरेपी रकम', subtotal: 'उपजम्मा', taxable: 'कर लाग्ने रकम', taxAmount: 'कर रकम', grandTotal: 'कुल जम्मा', paid: 'भुक्तानी भएको', remaining: 'बाँकी', preparedBy: 'तयार गर्ने', customerSignature: 'ग्राहकको हस्ताक्षर', authorizedSignature: 'अधिकृतको हस्ताक्षर', companyStamp: 'कम्पनीको छाप', generatedBy: 'KDS बिलिङ प्रणालीबाट तयार'
  } : {
    invoice: 'INVOICE', invoiceNo: 'Invoice #', billNo: 'Bill #', date: 'Date', due: 'Due', billTo: 'Bill To', phone: 'Phone', paymentStatus: 'Payment Status',
    product: 'Product / Service', qty: 'Qty', unit: 'Unit', rate: 'Rate', discount: 'Disc.', total: 'Total', noItems: 'No items', remarks: 'Remarks', amountWords: 'Amount in words', subtotal: 'Subtotal', taxable: 'Taxable Amount', taxAmount: 'Tax Amount', grandTotal: 'Grand Total', paid: 'Paid Amount', remaining: 'Remaining', preparedBy: 'Prepared By', customerSignature: 'Customer Signature', authorizedSignature: 'Authorized Signature', companyStamp: 'Company Stamp', generatedBy: 'Generated by KDS Billing System'
  };
  const {
    invoiceNumber = "DRAFT",
    billNumber = "",
    company = {},
    customer = {},
    billDate,
    dueDate,
    remarks = "",
    items = [],
    totals = {},
    paymentStatus = "unpaid",
    creator = {},
    createdAt
  } = invoice;

  const itemRows = items.length
    ? items.map((item, idx) => `
        <tr>
          <td class="center">${idx + 1}</td>
          <td>
            <strong>${escapeHtml(item.productName)}</strong>
            ${item.description ? `<br><small>${escapeHtml(item.description)}</small>` : ""}
          </td>
          <td class="center">${item.quantity}</td>
          <td class="center">${escapeHtml(item.unit)}</td>
          <td class="right">${currency.format(item.rate || 0)}</td>
          <td class="right">${currency.format(item.discount || 0)}</td>
          <td class="right"><strong>${currency.format(item.total || 0)}</strong></td>
        </tr>`).join("")
    : `<tr><td colspan="7" class="center muted">${l.noItems}</td></tr>`;

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>Invoice ${escapeHtml(invoiceNumber)}</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    @font-face { font-family: 'Noto Sans Devanagari'; src: url(data:font/woff2;base64,${devanagariFont}) format('woff2'); font-weight: 400; }
    body { font-family: 'Noto Sans Devanagari', 'Segoe UI', Arial, sans-serif; font-size: 11px; color: #1e293b; line-height: 1.5; }
    .invoice { max-width: 210mm; margin: 0 auto; }

    .header { background: #fff; color: #1e293b; padding: 20px 20px 18px; display: flex; justify-content: space-between; align-items: flex-start; gap: 28px; border-bottom: 1px solid #e2e8f0; }
    .header > div { flex: 1; min-width: 0; }
    .header h1 { font-size: 22px; margin-bottom: 4px; }
    .header p { font-size: 10px; color: #475569; margin-top: 3px; }
    .header-right { text-align: right; }
    .header-right .title { font-size: 20px; font-weight: bold; letter-spacing: 2px; }

    .parties { display: flex; justify-content: space-between; padding: 16px 24px; border-bottom: 1px solid #e2e8f0; }
    .label { font-size: 9px; text-transform: uppercase; letter-spacing: 1px; color: #94a3b8; font-weight: 600; margin-bottom: 4px; }
    .status { display: inline-block; padding: 3px 10px; border-radius: 12px; font-size: 9px; font-weight: 700; text-transform: uppercase;
              color: white; background: ${statusColor(paymentStatus)}; }

    .items { padding: 10px 18px; }
    table { width: 100%; border-collapse: collapse; }
    th { background: #f1f5f9; padding: 8px 6px; text-align: left; font-size: 9px; text-transform: uppercase;
         letter-spacing: 0.5px; color: #64748b; border: 1px solid #e2e8f0; }
    td { padding: 5px 6px; border: 1px solid #e2e8f0; vertical-align: top; }
    tr { page-break-inside: avoid; }
    thead { display: table-header-group; }
    .center { text-align: center; }
    .right { text-align: right; }
    .muted { color: #94a3b8; }

    .summary { display: flex; justify-content: space-between; padding: 0 24px 16px; gap: 24px; }
    .summary-left { flex: 1; }
    .summary-right { width: 220px; }
    .summary-row { display: flex; justify-content: space-between; padding: 4px 0; font-size: 11px; }
    .summary-row.grand { border-top: 2px solid #12355b; margin-top: 6px; padding-top: 8px; font-weight: bold; font-size: 13px; color: #12355b; }
    .words { font-style: italic; color: #64748b; font-size: 10px; margin-top: 8px; }

    .signatures { display: flex; justify-content: space-between; padding: 20px 24px; border-top: 1px solid #e2e8f0; }
    .sig-block { width: 22%; }
    .sig-line { border-top: 1px solid #64748b; margin-top: 40px; padding-top: 4px; font-size: 10px; }
    .stamp { border: 1px dashed #cbd5e1; height: 50px; margin-top: 8px; border-radius: 4px; }

    .footer { background: #f8fafc; padding: 10px 24px; font-size: 9px; color: #94a3b8;
              display: flex; justify-content: space-between; border-top: 1px solid #e2e8f0; }
  </style>
</head>
<body>
  <div class="invoice">
    <div class="header">
      <div>
        <h1>${escapeHtml(company.name || "Company Name")}</h1>
        ${company.pan ? `<p style="font-weight:700;color:#fff">PAN: ${escapeHtml(company.pan)}</p>` : ""}
        <p>${escapeHtml(company.address || "")}</p>
        <p>${[company.phone, company.email].filter(Boolean).map(escapeHtml).join(" · ")}</p>
      </div>
      <div class="header-right">
        <div class="title">${l.invoice}</div>
        <p style="margin-top:8px">${l.invoiceNo}: <strong>${escapeHtml(invoiceNumber)}</strong></p>
        ${billNumber ? `<p>${l.billNo}: <strong>${escapeHtml(billNumber)}</strong></p>` : ""}
        <p>${l.date}: ${formatDate(billDate, language)}</p>
        ${dueDate ? `<p>${l.due}: ${formatDate(dueDate, language)}</p>` : ""}
        <div style="border-top:1px solid rgba(255,255,255,.3);margin-top:8px;padding-top:8px">
          <p style="text-transform:uppercase;letter-spacing:1px;font-size:9px;color:#64748b">${l.billTo}</p>
          <p style="font-weight:700;color:#1e293b">${escapeHtml(customer.name || "")}</p>
          <p>${escapeHtml(customer.address || "")}</p>
          ${customer.phone ? `<p>${l.phone}: ${escapeHtml(customer.phone)}</p>` : ""}
          <p style="margin-top:4px;text-transform:uppercase;letter-spacing:1px;font-size:9px">${l.paymentStatus}</p>
          <p style="font-weight:700;color:#1e293b;text-transform:capitalize">${escapeHtml(paymentStatus)}</p>
        </div>
      </div>
    </div>

    <div class="items">
      <table>
        <thead>
          <tr>
            <th style="width:4%">#</th>
            <th style="width:28%">${l.product}</th>
            <th style="width:8%" class="center">${l.qty}</th>
            <th style="width:8%" class="center">${l.unit}</th>
            <th style="width:12%" class="right">${l.rate}</th>
            <th style="width:10%" class="right">${l.discount}</th>
            <th style="width:16%" class="right">${l.total}</th>
          </tr>
        </thead>
        <tbody>${itemRows}</tbody>
      </table>
    </div>

    <div class="summary">
      <div class="summary-left">
        ${remarks ? `<div class="label">${l.remarks}</div><p style="margin-bottom:8px">${escapeHtml(remarks)}</p>` : ""}
        <p class="words">${l.amountWords}: <strong>${amountToWords(totals.grandTotal || 0)}</strong></p>
      </div>
      <div class="summary-right">
        <div class="summary-row"><span>${l.subtotal}</span><span>${currencySymbol} ${currency.format(totals.subtotal || 0)}</span></div>
        <div class="summary-row"><span>${l.discount}</span><span>${currencySymbol} ${currency.format(totals.discount || 0)}</span></div>
        <div class="summary-row"><span>${l.taxable}</span><span>${currencySymbol} ${currency.format(totals.taxableAmount || 0)}</span></div>
        <div class="summary-row"><span>${l.taxAmount} (${totals.taxRate || 0}%)</span><span>${currencySymbol} ${currency.format(totals.tax || 0)}</span></div>
        <div class="summary-row grand"><span>${l.grandTotal}</span><span>${currencySymbol} ${currency.format(totals.grandTotal || 0)}</span></div>
        <div class="summary-row"><span>${l.paid}</span><span>${currencySymbol} ${currency.format(totals.paidAmount || 0)}</span></div>
        <div class="summary-row"><span>${l.remaining}</span><span>${currencySymbol} ${currency.format(totals.remainingAmount || 0)}</span></div>
      </div>
    </div>

    <div class="signatures">
      <div class="sig-block">
        <div class="label">${l.preparedBy}</div>
        <div class="sig-line">${escapeHtml(creator.name || "—")}</div>
        <p class="muted">${formatDate(createdAt || billDate, language)}</p>
      </div>
      <div class="sig-block">
        <div class="label">${l.customerSignature}</div>
        <div class="sig-line">&nbsp;</div>
      </div>
      <div class="sig-block">
        <div class="label">${l.authorizedSignature}</div>
        <div class="sig-line">&nbsp;</div>
      </div>
      <div class="sig-block">
        <div class="label">${l.companyStamp}</div>
        <div class="stamp"></div>
      </div>
    </div>

    <div class="footer">
      <span>${l.generatedBy}</span>
      <span>${formatDate(new Date(), language)}</span>
    </div>
  </div>
</body>
</html>`;
};
